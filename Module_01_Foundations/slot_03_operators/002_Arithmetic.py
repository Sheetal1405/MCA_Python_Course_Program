x = 10
y = 3

sum = x+y
print("Sum of two numbers:", sum)

diff = x - y
print("Difference of two numbers:", diff)

prod = x*y
print("Product of two numbers:", prod)

quot = x/y
print("Quotient of two numbers:", quot)

modulus = x%y
print("Modulus of two numbers:", modulus)

exponent = x**y
print("Exponent of two numbers:", exponent)

fld = x//y
print("Floor division of two numbers:", fld)